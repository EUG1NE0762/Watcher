// Generates supabase/seed.sql from the JSON data files and the shared engine.
// Usage: node scripts/generate-seed.mjs [--no-demo] [--out <path>]
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { buildAreas, computeAllBands, DEMO_SOURCE, generateDemoIncidents } from '../packages/scoring/src/index.ts';
import { DATA, loadAreaSeeds, readJson, ROOT } from './lib.mjs';

const withDemo = !process.argv.includes('--no-demo');
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (xs) => `array[${xs.map(q).join(', ')}]::text[]`;

const sources = readJson(join(DATA, 'sources.json'));
const areas = buildAreas(loadAreaSeeds());
const now = new Date();
const lines = [
  '-- GENERATED by scripts/generate-seed.mjs. Do not edit by hand; edit supabase/seed/data/*.json instead.',
  `-- Generated at ${now.toISOString()}`,
  'begin;',
  '',
  '-- Sources (real outlets; no incidents are attributed to them by this seed)',
];
for (const s of sources) {
  lines.push(
    `insert into public.sources (id, name, type, base_url, credibility_weight, requires_corroboration, feeds) values (${q(s.id)}, ${q(s.name)}, ${q(s.type)}, ${q(s.base_url)}, ${s.credibility_weight}, ${!!s.requires_corroboration}, ${arr(s.feeds ?? [])}) on conflict (id) do update set name = excluded.name, type = excluded.type, base_url = excluded.base_url, credibility_weight = excluded.credibility_weight, requires_corroboration = excluded.requires_corroboration, feeds = excluded.feeds;`,
  );
}
lines.push('', '-- Areas (approximate boundaries; replace with surveyed polygons when available)');
for (const a of areas) {
  const geo = JSON.stringify({ type: 'Polygon', coordinates: [a.polygon] });
  lines.push(
    `insert into public.areas (id, name, city, province, area_type, aliases, description, geom, centroid) values (${q(a.id)}, ${q(a.name)}, ${q(a.city)}, ${q(a.province)}, ${q(a.area_type)}, ${arr(a.aliases)}, ${q(a.description)}, extensions.st_setsrid(extensions.st_geomfromgeojson(${q(geo)}), 4326), extensions.st_setsrid(extensions.st_makepoint(${a.centroid.lng}, ${a.centroid.lat}), 4326)) on conflict (id) do update set name = excluded.name, aliases = excluded.aliases, description = excluded.description, area_type = excluded.area_type, geom = excluded.geom, centroid = excluded.centroid;`,
  );
}

if (withDemo) {
  const incidents = generateDemoIncidents(areas, readJson(join(DATA, 'demo-profiles.json')), now);
  lines.push(
    '',
    '-- ==========================================================================',
    '-- DEMO DATA. Illustrative only, NOT real incidents. is_demo = true on every row,',
    '-- attributed to the fictional "Watcher Demo Dataset" source. Remove with:',
    "--   delete from public.incidents where is_demo; delete from public.sources where id = 'demo';",
    '-- ==========================================================================',
    `insert into public.sources (id, name, type, base_url, credibility_weight) values (${q(DEMO_SOURCE.id)}, ${q(DEMO_SOURCE.name)}, 'demo', ${q(DEMO_SOURCE.base_url)}, 1) on conflict (id) do nothing;`,
    "delete from public.incidents where is_demo;",
  );
  for (const i of incidents) {
    lines.push(
      `insert into public.incidents (id, area_id, category, severity, substance, occurred_at, published_at, source_id, source_url, summary, confidence, status, is_demo, raw_text_hash, corroboration_count) values (${q(i.id)}, ${q(i.area_id)}, ${q(i.category)}, ${i.severity}, ${q(i.substance)}, ${q(i.occurred_at)}, ${q(i.published_at)}, ${q(i.source_id)}, ${q(i.source_url)}, ${q(i.summary)}, ${q(i.confidence)}, 'verified', true, ${q(`demo:${i.id}`)}, ${i.corroboration_count ?? 1});`,
    );
  }
  lines.push('', '-- Scores computed by the shared engine (recompute-scores refreshes these daily)');
  for (const a of areas) {
    const all = computeAllBands(
      incidents.filter((i) => i.area_id === a.id),
      { areaId: a.id, areaType: a.area_type, sources: [DEMO_SOURCE], now },
    );
    for (const s of Object.values(all)) {
      lines.push(
        `insert into public.risk_scores (area_id, time_band, score, rating, breakdown, computed_at) values (${q(s.area_id)}, ${q(s.time_band)}, ${s.score ?? 'null'}, ${q(s.rating)}, ${q(JSON.stringify(s.breakdown))}::jsonb, ${q(s.computed_at)}) on conflict (area_id, time_band) do update set score = excluded.score, rating = excluded.rating, breakdown = excluded.breakdown, computed_at = excluded.computed_at;`,
      );
    }
  }
}
lines.push('', 'commit;', '');
const outArg = process.argv.indexOf('--out');
const out = outArg > 0 ? process.argv[outArg + 1] : join(ROOT, 'supabase', 'seed.sql');
writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${out} (${areas.length} areas${withDemo ? ', demo incidents included' : ''})`);
